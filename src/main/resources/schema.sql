CREATE TABLE IF NOT EXISTS "registered_services" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    base_url VARCHAR(255) NOT NULL,
    health_check_path VARCHAR(255) NOT NULL,
    owner_team VARCHAR(120) NOT NULL,
    status VARCHAR(40) DEFAULT 'UNKNOWN',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_registered_services_name ON "registered_services"(name);

CREATE TABLE IF NOT EXISTS "gateway_routes" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id VARCHAR(120) NOT NULL,
    path VARCHAR(255) NOT NULL,
    service_id BIGINT NOT NULL,
    strip_prefix INT DEFAULT 0,
    auth_required BOOLEAN DEFAULT FALSE,
    rate_limit_per_minute INT,
    enabled BOOLEAN DEFAULT TRUE,
    CONSTRAINT fk_gateway_routes_service FOREIGN KEY (service_id) REFERENCES "registered_services"(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_gateway_routes_route_id ON "gateway_routes"(route_id);

-- Phase 8: Canary Routing
-- Each row assigns a percentage weight to a (route, service) pair.
-- Weights for a given route_id should sum to 100.
CREATE TABLE IF NOT EXISTS "canary_targets" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    weight INT NOT NULL,
    enabled BOOLEAN DEFAULT TRUE,
    CONSTRAINT fk_canary_route FOREIGN KEY (route_id) REFERENCES "gateway_routes"(id),
    CONSTRAINT fk_canary_service FOREIGN KEY (service_id) REFERENCES "registered_services"(id),
    CONSTRAINT uq_canary_route_service UNIQUE (route_id, service_id)
);

CREATE INDEX IF NOT EXISTS idx_canary_targets_route_id ON "canary_targets"(route_id);

-- Multi-tenancy: teams own services (and, through them, routes and canary targets).
CREATE TABLE IF NOT EXISTS "teams" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_teams_name ON "teams"(name);

CREATE TABLE IF NOT EXISTS "app_users" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL,
    team_id BIGINT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_app_users_team FOREIGN KEY (team_id) REFERENCES "teams"(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_app_users_username ON "app_users"(username);

-- Only the SHA-256 hash of each login token is stored.
CREATE TABLE IF NOT EXISTS "auth_tokens" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_auth_tokens_user FOREIGN KEY (user_id) REFERENCES "app_users"(id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_auth_tokens_hash ON "auth_tokens"(token_hash);

ALTER TABLE "registered_services" ADD COLUMN IF NOT EXISTS team_id BIGINT REFERENCES "teams"(id);
ALTER TABLE "registered_services" ADD COLUMN IF NOT EXISTS last_checked_at TIMESTAMP WITH TIME ZONE;

-- Snapshots deliberately survive deletion of the actor, service, or route.
CREATE TABLE IF NOT EXISTS audit_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL,
    actor_username VARCHAR(120) NOT NULL,
    team_id BIGINT NOT NULL,
    route_pk BIGINT NOT NULL,
    route_id VARCHAR(120) NOT NULL,
    action VARCHAR(40) NOT NULL,
    details TEXT NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_entries_team_id ON audit_entries(team_id, id DESC);
