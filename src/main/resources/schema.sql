CREATE TABLE IF NOT EXISTS "registered_services" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    base_url VARCHAR(255) NOT NULL,
    health_check_path VARCHAR(255) NOT NULL,
    owner_team VARCHAR(120) NOT NULL,
    status VARCHAR(40) DEFAULT 'UNKNOWN',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_registered_services_name ON "registered_services"(name);

CREATE TABLE IF NOT EXISTS "gateway_routes" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id VARCHAR(120) NOT NULL,
    path VARCHAR(255) NOT NULL,
    service_id BIGINT NOT NULL,
    strip_prefix INT DEFAULT 0,
    auth_required BOOLEAN DEFAULT FALSE,
    rate_limit_per_minute INT,
    enabled BOOLEAN DEFAULT TRUE,
    CONSTRAINT fk_gateway_routes_service FOREIGN KEY (service_id) REFERENCES "registered_services"(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_gateway_routes_route_id ON "gateway_routes"(route_id);

-- Phase 8: Canary Routing
-- Each row assigns a percentage weight to a (route, service) pair.
-- Weights for a given route_id should sum to 100.
CREATE TABLE IF NOT EXISTS "canary_targets" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    weight INT NOT NULL,
    enabled BOOLEAN DEFAULT TRUE,
    CONSTRAINT fk_canary_route FOREIGN KEY (route_id) REFERENCES "gateway_routes"(id),
    CONSTRAINT fk_canary_service FOREIGN KEY (service_id) REFERENCES "registered_services"(id),
    CONSTRAINT uq_canary_route_service UNIQUE (route_id, service_id)
);

CREATE INDEX IF NOT EXISTS idx_canary_targets_route_id ON "canary_targets"(route_id);
